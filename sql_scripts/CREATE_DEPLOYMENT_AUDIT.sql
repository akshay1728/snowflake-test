-- Run once as ACCOUNTADMIN (or an administrator with the required privileges).
-- This bootstrap script is under sql_scripts/, not the Schemachange root folder.

CREATE SCHEMA IF NOT EXISTS NAS_ADMIN.SCHEMACHANGE;

CREATE TABLE IF NOT EXISTS NAS_ADMIN.SCHEMACHANGE.DEPLOYMENT_AUDIT
(
    DEPLOYMENT_ID              VARCHAR(36) NOT NULL,
    ENVIRONMENT                VARCHAR(20) NOT NULL,
    GITHUB_REPOSITORY          VARCHAR(255),
    GITHUB_WORKFLOW            VARCHAR(255),
    GITHUB_RUN_ID              NUMBER(38,0),
    GITHUB_RUN_NUMBER          NUMBER(38,0),
    GITHUB_RUN_URL             VARCHAR(2048),
    SOURCE_BRANCH              VARCHAR(255),
    COMMIT_SHA                 VARCHAR(40),
    PR_NUMBER                  NUMBER(38,0),
    PR_TITLE                   VARCHAR(2048),
    PR_URL                     VARCHAR(2048),
    PR_AUTHOR                  VARCHAR(255),
    PR_MERGED_BY               VARCHAR(255),
    PR_MERGED_AT               TIMESTAMP_TZ,
    PR_APPROVED_BY              VARCHAR(4000),
    PR_METADATA                VARIANT,
    PR_APPROVED_REVIEWS        VARIANT,
    ENVIRONMENT_APPROVED_BY    VARCHAR(2000),
    ENVIRONMENT_APPROVAL_COMMENT VARCHAR(4000),
    ENVIRONMENT_APPROVALS      VARIANT,
    APPROVALS_RETRIEVED_AT     TIMESTAMP_TZ,
    DEPLOYMENT_ACTOR           VARCHAR(255),
    DEPLOYMENT_STATUS          VARCHAR(30),
    DEPLOYMENT_MODE            VARCHAR(30),
    SCHEMACHANGE_VERSION       VARCHAR(50),
    RECORDED_AT                TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

-- Grant only the permissions needed by the deployment service roles.
GRANT USAGE ON DATABASE NAS_ADMIN TO ROLE FR_DEPLOYMENT_DEV;
GRANT USAGE ON SCHEMA NAS_ADMIN.SCHEMACHANGE TO ROLE FR_DEPLOYMENT_DEV;
GRANT INSERT ON TABLE NAS_ADMIN.SCHEMACHANGE.DEPLOYMENT_AUDIT TO ROLE FR_DEPLOYMENT_DEV;

GRANT USAGE ON DATABASE NAS_ADMIN TO ROLE FR_DEPLOYMENT_UAT;
GRANT USAGE ON SCHEMA NAS_ADMIN.SCHEMACHANGE TO ROLE FR_DEPLOYMENT_UAT;
GRANT INSERT ON TABLE NAS_ADMIN.SCHEMACHANGE.DEPLOYMENT_AUDIT TO ROLE FR_DEPLOYMENT_UAT;

GRANT USAGE ON DATABASE NAS_ADMIN TO ROLE FR_DEPLOYMENT_PROD;
GRANT USAGE ON SCHEMA NAS_ADMIN.SCHEMACHANGE TO ROLE FR_DEPLOYMENT_PROD;
GRANT INSERT ON TABLE NAS_ADMIN.SCHEMACHANGE.DEPLOYMENT_AUDIT TO ROLE FR_DEPLOYMENT_PROD;
